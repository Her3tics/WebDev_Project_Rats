function darkMode()
{
    var element = document.body;
    var content = document.getElementById("DarkMode text");
    element.className = "dark-mode";
    let imageMode = getElementById("mode")

    imageMode.src = "https://img.magnific.com/free-photo/3d-car-with-simple-background_23-2150796882.jpg"
}



